"""
flow._client — High-level FlowClient combining FlowAPI + FlowUI + UIInterceptor.

Architecture:
    FlowAPI        → direct REST/tRPC calls (credits, poll, model config) — NO reCAPTCHA
    FlowUI         → Playwright UI automation (navigate, click buttons, fill inputs)
    UIInterceptor  → captures aisandbox API calls triggered by UI clicks (gets valid reCAPTCHA)
    FlowClient     → combines all three into clean async methods

The key insight:
    All generation endpoints need valid reCAPTCHA Enterprise tokens.
    Tokens from page.evaluate() are rejected (Playwright detected → low score).
    Tokens generated by REAL button clicks PASS.
    Solution: click buttons, intercept the resulting API call.

Usage:
    async with await FlowClient.create("project-uuid") as client:
        job = await client.generate_video("golden lotus at dawn")
        status = await client.wait_for_video(job)
        path = await client.download(status.media_name, "./output/video.mp4")
"""
