class FlowClient:
    """
    High-level async client for Google Flow AI.

    All generation methods use UI automation + network interception to get
    valid reCAPTCHA tokens (required by aisandbox-pa.googleapis.com).

    Read-only methods (credits, poll, model_config) use the direct REST API.
    """

    def __init__(
        self,
        api: FlowAPI,
        bm: BrowserManager,
        project_id: str,
        workflow_id: Optional[str] = None,
    ):
        self._api       = api
        self._bm        = bm
        self.project_id = project_id
        self.workflow_id = workflow_id
        self._ui        = FlowUI()
        self._project_url = f"https://labs.google/fx/tools/flow/project/{project_id}"

    # ── Factory ────────────────────────────────────────────────────────────────

    @classmethod
    async def create(
        cls,
        project_id: Optional[str] = None,
        workflow_id: Optional[str] = None,
        *,
        headless: bool = True,
        cdp_url: Optional[str] = None,
        timeout_s: int = 300,
    ) -> "FlowClient":
        """
        Create and initialize a FlowClient.

        Args:
            project_id:  Flow project UUID. Defaults to the saved active project.
            workflow_id: Flow workflow UUID (used for edit-page operations).
            headless:    Launch browser in headless mode (default True).
            cdp_url:     Connect to an existing Chrome CDP port, e.g. "http://127.0.0.1:9222".
                         Useful in development; bypasses login but reCAPTCHA may fail.
            timeout_s:   Default generation timeout (seconds).
        """
        cfg = load_config()
        pid = project_id or get_active_project()[0] or ""

        if cdp_url:
            bm = BrowserManager.from_cdp(cdp_url)
        else:
            bm = BrowserManager(headless=headless)
        await bm.start()

        api = FlowAPI(bm, project_id=pid, default_timeout_s=timeout_s)

        # Navigate to project page to load session + reCAPTCHA
        page = await bm.page()
        if "labs.google" not in page.url:
            proj_url = f"https://labs.google/fx/tools/flow/project/{pid}"
            await page.goto(proj_url, wait_until="domcontentloaded", timeout=20_000)
            await asyncio.sleep(2)

        return cls(api, bm, pid, workflow_id)

